const dicts: Record<Lang, Record<Key, string>> = { pt, es };

export type Translate = (key: Key, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): Translate {
  const dict = dicts[lang] ?? pt;
  return (key, vars) => {
    const s = dict[key] ?? pt[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`)) : s;
  };
}

export function localeOf(lang: Lang): string {
  return lang === 'es' ? 'es-ES' : 'pt-BR';
}

/** "novembro de 2026" → "Novembro de 2026". CSS `capitalize` would give "Novembro De 2026". */
export function capFirst(s: string): string {
  return s.charAt(0).toLocaleUpperCase() + s.slice(1);
}

export function hasKey(k: string): k is Key {
  return k in pt;
}
